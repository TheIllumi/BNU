/*
Program 17:
Design a program which converts the name “ALI” into 
the ASCII codes of each letter
*/

#include <iostream>
using namespace std;

int main()
{
	char a = 'A';
	char l = 'L';
	char i = 'I'; 
    cout << "The ASCII value of " << a << " is " << int(a)<<endl;
	cout << "The ASCII value of " << l << " is " << int(l)<<endl;
	cout << "The ASCII value of " << i << " is " << int(i)<<endl; 
	return 0;
}